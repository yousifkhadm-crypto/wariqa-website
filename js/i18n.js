function getPreferredLanguage() {
  try {
    return localStorage.getItem('waraq-language') || 'ar';
  } catch (error) {
    return 'ar';
  }
}

function setLanguage(lang) {
  const selectedLanguage = translations[lang] ? lang : 'ar';
  document.documentElement.lang = selectedLanguage;
  document.documentElement.dir = selectedLanguage === 'en' ? 'ltr' : 'rtl';
  document.body.dir = document.documentElement.dir;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (translations[selectedLanguage][key]) {
      element.textContent = translations[selectedLanguage][key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (translations[selectedLanguage][key]) {
      element.placeholder = translations[selectedLanguage][key];
    }
  });

  document.querySelectorAll('.suggestion').forEach((button, index) => {
    const suggestions = translations[selectedLanguage].assistantSuggestions || [];
    if (suggestions[index]) {
      button.textContent = suggestions[index];
      button.dataset.suggestion = suggestions[index];
    }
  });

  document.querySelectorAll('.lang-btn').forEach((button) => {
    const isActive = button.dataset.lang === selectedLanguage;
    button.classList.toggle('active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });

  document.dispatchEvent(new CustomEvent('waraq-language-changed', { detail: { lang: selectedLanguage } }));

  try {
    localStorage.setItem('waraq-language', selectedLanguage);
  } catch (error) {
    // Ignore storage issues in restricted environments.
  }
}

function initLanguageSwitcher() {
  document.querySelectorAll('.lang-btn').forEach((button) => {
    button.addEventListener('click', () => setLanguage(button.dataset.lang));
  });
}

document.addEventListener('DOMContentLoaded', () => {
  initLanguageSwitcher();
  setLanguage(getPreferredLanguage());
});
